'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const Catalog=require('./catalog.js');
const data=JSON.parse(fs.readFileSync(__dirname+'/data/catalog.json','utf8'));
const records=data.fragrances;
assert.equal(records.length,data.metadata.records);
assert.equal(records.filter(f=>f.image).length,data.metadata.withImages);
assert.equal(new Set(records.map(f=>f.id)).size,records.length);
assert(records.every(f=>f.brand&&f.name&&/^obf-\d+$/.test(f.id)&&f.sourceUrl.startsWith('https://world.openbeautyfacts.org/product/')));
assert(records.filter(f=>f.image).every(f=>new URL(f.image).hostname==='images.openbeautyfacts.org'&&f.imageLicense==='CC-BY-SA-3.0'));
assert.equal(Catalog.filter([{brand:'Élan',name:'Boisé',barcode:'1234'}],{query:'elan boise'}).length,1);
assert.equal(Catalog.filter(records,{query:records[0].barcode})[0].id,records[0].id);
assert(Catalog.filter(records,{imagesOnly:true}).every(f=>f.image));
const brand=records[0].brand;assert(Catalog.filter(records,{brand}).every(f=>f.brand===brand));
assert.equal(Catalog.filter(records,{query:'no-such-fragrance-xyz'}).length,0);
assert.equal(Catalog.page(records).items.length,24);
const last=Catalog.page(records,999);assert.equal(last.current,last.pages);assert(last.items.length>0&&last.items.length<=24);
assert.equal(Catalog.page([],999).current,1);
console.log(`Catalog checks passed: ${records.length} unique product IDs, licensing, search, filters and pagination.`);
